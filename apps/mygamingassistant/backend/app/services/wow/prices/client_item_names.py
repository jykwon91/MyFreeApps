"""Item names from the Forever client, for auction prices.

Blizzard's auction data carries item ids only. The committed
``backend/data/wow/item_names.json`` (generated by
``python -m scripts.wow_item_names.build``) names them when prices are read.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

# Path: app/services/wow/prices/ → parents[4] = backend/
_DATA_PATH = Path(__file__).resolve().parents[4] / "data" / "wow" / "item_names.json"


@dataclass(frozen=True)
class ClientItemNames:
    # The client build the names came from — part of the price ETag, so a new
    # names file reaches browsers holding a cached response.
    client_build: str
    names: dict[int, str]

    def name_for(self, item_id: int) -> str:
        """The client's name for the item, else empty."""
        return self.names.get(item_id, "")


@lru_cache(maxsize=1)
def client_item_names() -> ClientItemNames:
    payload = json.loads(_DATA_PATH.read_text(encoding="utf-8"))
    return ClientItemNames(
        client_build=payload["clientBuild"],
        names={int(item_id): name for item_id, name in payload["names"].items()},
    )
