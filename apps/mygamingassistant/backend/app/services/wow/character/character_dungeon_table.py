"""The committed dungeon list (``backend/data/wow/character_dungeons.json``).

Generated by ``python -m scripts.wow_character_dungeons.build``, which checks
every statistic id against the Forever client.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

from app.services.wow.character.character_dungeon_definition import CharacterDungeonDefinition

# Path: app/services/wow/character/ → parents[4] = backend/
_DATA_PATH = Path(__file__).resolve().parents[4] / "data" / "wow" / "character_dungeons.json"


@lru_cache(maxsize=1)
def character_dungeon_table() -> tuple[CharacterDungeonDefinition, ...]:
    """Every dungeon in level order."""
    payload = json.loads(_DATA_PATH.read_text(encoding="utf-8"))
    return tuple(
        CharacterDungeonDefinition(
            name=row["name"],
            wing=row["wing"],
            classic=row["classic"],
            boss=row["boss"],
            statistic_ids=tuple(row["statisticIds"]),
            level_min=row["levelMin"],
            level_max=row["levelMax"],
            required_level=row["requiredLevel"],
        )
        for row in payload["dungeons"]
    )
