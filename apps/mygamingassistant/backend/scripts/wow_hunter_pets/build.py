HUNTER_PETS_DIR = WOW_DATA_DIR / "hunterPets"
FOREVER_PATH = HUNTER_PETS_DIR / "hunterPets.json"
CLASSIC_DIR = HUNTER_PETS_DIR / "classic"
BEASTS_PATH = CLASSIC_DIR / "tamableBeasts.json"
FOREVER_TABLES = (*FOREVER_BOOK_TABLES, "SpellLevels", "SkillLineAbility")
BEAST_COLUMNS = ["id", "name", "family", "minLevel", "maxLevel", "attackMs", "zones", "teaches"]
SEEN_COLUMNS = ["id", "name", "family", "seenOn"]
RANK_COLUMNS = ["spell", "level", "text", "new", "families"]

CLASSIC_README = """# Hunter pets — Classic tamable beasts

`tamableBeasts.json` lists every Classic creature a hunter can tame
(`creature_template` `CreatureType` 1 with `CreatureTypeFlags` bit 0 set) that
belongs to one of the guide's families and has a spawn. For each: name, family
id (`Family`), level range (`MinLevel` / `MaxLevel`), attack speed in
milliseconds (`MeleeBaseAttackTime`), the three places it spawns most
(`creature`: seasonal-event spawns left out; a continent spawn is placed on the
World Map, an instance spawn keeps its instance map) and the pet ability ranks
it teaches. The ranks are its `PetSpellDataId` looked up in the Classic Era
client's `CreatureSpellData` ({era_branch} {era_build}, wago.tools). A beast
with no spawn is left out.

Derived from [cmangos classic-db](https://github.com/cmangos/classic-db) at
commit `{commit}`, licensed GPL-3.0 — see `LICENSE`. No cmangos code is used.
Forever may differ: the page tags all of it "Classic data".

Generated by `backend/scripts/wow_hunter_pets/build.py`. Never hand-edit.
"""


def family_ids_for(ability: Ability, families: list[Family]) -> list[int]:
    if GENERIC_SKILL_LINE in ability.lines:
        return [f.id for f in families]
    return [f.id for f in families if f.skill_line in ability.lines]


def ability_doc(
    ability: Ability,
    families: list[Family],
    texts: dict[int, str | None],
    icons: dict[int, int],
) -> dict[str, Any]:
    owners = family_ids_for(ability, families)
    ranks = []
    for r in ability.ranks:
        rank_owners = family_ids_for(Ability(ability.name, ability.slug, [r], r.lines, r.is_new), families)
        ranks.append([
            r.spell, r.level, texts.get(r.spell), int(r.is_new and not ability.is_new),
            None if rank_owners == owners else rank_owners,
        ])
    return {
        "slug": ability.slug,
        "name": ability.name,
        "icon": next((icons[r.spell] for r in ability.ranks if r.spell in icons), 0),
        "new": ability.is_new,
        "families": owners,
        "ranks": ranks,
    }


def beast_row(b: Beast) -> list[Any]:
    return [b.id, b.name, b.family, b.min_level, b.max_level, b.attack_ms, b.zones, b.teaches]


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the WoW Forever Hunter pets guide's data.")
    parser.add_argument("--hotfix-cache", help="the Forever client's _forever_/Cache/ADB/enUS/DBCache.bin")
    parser.add_argument("--creature-cache", help="the Forever client's Cache/WDB/enUS/creaturecache.wdb")
    args = parser.parse_args()

    forever = load_forever_tables(hotfix_cache_path(args.hotfix_cache), FOREVER_TABLES)
    tables = {name: forever.table(name) for name in FOREVER_TABLES}
    cache, seen_on = read_creature_cache(creature_cache_path(args.creature_cache))
    era = {"branch": WAGO_ERA_BRANCH, "build": WAGO_ERA_BUILD}

    classic_family_ids = {int(r["ID"]) for r in wago_table("CreatureFamily", **era)}
    families = build_families(
        wago_table("CreatureFamily"), classic_family_ids, wago_table("ItemPetFood"),
        tables["SkillLineAbility"], tables["SpellEffect"],
    )
    family_ids = {f.id for f in families}

    names = {int(r["ID"]): r["Name_lang"] for r in tables["SpellName"]}
    levels = {int(r["SpellID"]): int(r["SpellLevel"] or 0) for r in tables["SpellLevels"]}
    pet_lines = [f.skill_line for f in families]
    line_set = set(pet_lines) | {GENERIC_SKILL_LINE}
    classic_spells = {int(r["Spell"]) for r in wago_table("SkillLineAbility", **era) if int(r["SkillLine"]) in line_set}
    abilities = build_abilities(tables["SkillLineAbility"], pet_lines, levels, names, classic_spells)
    book = forever_book(tables)
    icons = forever_icons(tables["SpellMisc"])
    texts = {r.spell: full_text(book, r.spell) for a in abilities for r in a.ranks}

    print("Reading cmangos classic-db...")
    dump = read_dump(cmangos_dump(), {"creature_template", "creature", "game_event_creature"})
    templates = tamable_templates(dump["creature_template"], family_ids)
    _entries, bounds = load_zones()
    art = WorldMapArt()

    def placer(continent: int, wx: float, wy: float) -> list[Any] | None:
        spot = place(bounds, art, continent, wx, wy, exclude=FOREVER_ONLY_ZONES)
        return None if spot is None else spot.as_row()

    zones = spawn_zones(
        dump["creature"], {int(t["Entry"]) for t in templates},
        event_only_guids(dump["game_event_creature"]), placer,
    )
    ability_spells = {r.spell for a in abilities for r in a.ranks}
    beasts, dropped = classic_beasts(
        templates, zones, pet_spell_lists(wago_table("CreatureSpellData", **era)), ability_spells,
    )
    map_names = {int(r["ID"]): r["MapName_lang"] for r in wago_table("Map")}
    zone_names = {str(b.ui_map_id): b.name for b in bounds}
    zone_names.update({instance_zone_key(m): map_names.get(m, f"Map {m}") for m in {
        int(k[1:]) for b in beasts for k in b.zones if k.startswith("m")
    }})
    used = {k for b in beasts for k in b.zones}

    earlier = earlier_seen_beasts(json.loads(FOREVER_PATH.read_text(encoding="utf-8"))) if FOREVER_PATH.is_file() else {}
    seen = seen_rows(cache, family_ids, seen_on, earlier)
    write_lines(FOREVER_PATH, {
        "source": f"{forever.source()}; the creature cache on the operator's machine (Cache/WDB/enUS/creaturecache.wdb)",
        "clientBuild": cache.build,
        "wagoBuild": WAGO_BUILD,
        "attribution": "Game data from the WoW Forever client. © Blizzard Entertainment.",
        "families": [
            {
                "id": f.id, "slug": f.slug, "name": f.name, "icon": f.icon, "diet": f.diet,
                "damage": f.damage, "armor": f.armor, "health": f.health, "new": f.is_new,
            }
            for f in families
        ],
        "rankColumns": RANK_COLUMNS,
        "abilities": [ability_doc(a, families, texts, icons) for a in abilities],
        "seenColumns": SEEN_COLUMNS,
        "seen": [b.as_row() for b in seen],
    }, "abilities")
    write_lines(BEASTS_PATH, {
        "source": {"repo": "cmangos/classic-db", "commit": CMANGOS_COMMIT, "license": "GPL-3.0-or-later"},
        "columns": BEAST_COLUMNS,
        "zones": {k: zone_names[k] for k in sorted(used)},
        "beasts": [beast_row(b) for b in beasts],
    }, "beasts")
    shutil.copyfile(CLASSIC_LICENSE, CLASSIC_DIR / "LICENSE")
    (CLASSIC_DIR / "README.md").write_text(
        CLASSIC_README.format(era_branch=WAGO_ERA_BRANCH, era_build=WAGO_ERA_BUILD, commit=CMANGOS_COMMIT),
        encoding="utf-8",
    )

    classic_ids = {b.id for b in beasts}
    unmatched = sum(
        1 for t in templates if int(t["PetSpellDataId"]) and int(t["Entry"]) in classic_ids
    ) - sum(1 for b in beasts if b.teaches)
    blank = sum(1 for t in texts.values() if t is None)
    print(
        f"{len(families)} families ({sum(f.is_new for f in families)} new), {len(abilities)} abilities, "
        f"{sum(len(a.ranks) for a in abilities)} ranks ({blank} without readable text); "
        f"{len(beasts)} Classic beasts ({len(dropped)} without a spawn left out, {unmatched} with pet spells matching no rank), "
        f"{sum(1 for b in beasts if b.teaches)} teach something; {len(seen)} seen in game "
        f"({sum(1 for c in seen if c.creature_id in classic_ids)} also in Classic) -> {HUNTER_PETS_DIR}"
    )
    no_modifiers = [f.name for f in families if f.damage is None]
    print(f"families without modifiers in the client: {no_modifiers}")


if __name__ == "__main__":
    main()
