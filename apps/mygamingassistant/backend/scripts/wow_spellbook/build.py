"""Build the WoW Forever Spellbook's data (``/wow-forever/spellbook/:class``).

Usage (from ``apps/mygamingassistant/backend``, after the Changes and Downrank builds)::

    python -m scripts.wow_spellbook.build [--hotfix-cache <DBCache.bin>]

Every spell each class's skill lines teach (``spells.py`` says which are kept),
from the Forever client with the hotfix layers the item build uses
(``--hotfix-cache``, else ``WOW_FOREVER_HOTFIX_CACHE``, else the default install
path; the run stops without it): names, ranks, levels (``SpellLevels``), icons
(``SpellMisc``), and each rank's tooltip with its tokens filled. A spell the
Changes vs Classic feed lists is marked changed / new; a spell with a downrank
family links to it; a talent's spell links to the talent calculator.

Writes:

* ``data/spellbook/<class>.json`` — the Forever client's spells, one per line.
* ``data/spellbook/classic/<class>.json`` — what only Classic data has: trainer
  costs and quest- / book-taught spells (cmangos classic-db ``npc_trainer`` /
  ``quest_template`` / ``item_template``), and for ranks the Forever client can't give in full,
  the Classic Era client's wording with cmangos' 1.12 numbers and cmangos'
  spell level — same spell id only, never another rank's. GPL-3.0, LICENSE +
  README next to it. The page tags all of it Classic data.

Game data © Blizzard Entertainment. Never hand-edit the output.
"""
from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path
from typing import Any

from scripts.wow_changes.spells import full_text
from scripts.wow_food.build import CLASSIC_LICENSE, WOW_DATA_DIR
from scripts.wow_gear.build import write_json
from scripts.wow_items.forever_items import hotfix_cache_path, load_forever_tables
from scripts.wow_macros.build import CLASS_LINES
from scripts.wow_spellbook.docs import ClassicFill, FieldCounts, change_info, spell_doc, write_lines
from scripts.wow_spellbook.spells import Learned, SpellFacts, SpellGaps, class_spells, talent_spells
from scripts.wow_spellbook.trainers import book_spells, quest_spells, teaching_map, trainer_costs
from scripts.wow_talents.books import FOREVER_BOOK_TABLES, classic_book, forever_book
from scripts.wow_world_map.sources import (
    CMANGOS_COMMIT,
    WAGO_BUILD,
    WAGO_ERA_BRANCH,
    WAGO_ERA_BUILD,
    cmangos_dump,
    wago_table,
)
from scripts.wow_world_map.sql_dump import read_dump

SPELLBOOK_DIR = WOW_DATA_DIR / "spellbook"
CLASSIC_DIR = SPELLBOOK_DIR / "classic"
CHANGED_SPELLS_FILE = WOW_DATA_DIR / "changes" / "classic" / "spells.json"
DOWNRANK_FILE = WOW_DATA_DIR / "downrank" / "spells.json"
FOREVER_TABLES = (*FOREVER_BOOK_TABLES, "SpellLevels", "SkillLineAbility", "Talent")

CLASSIC_README = """# Spellbook — Classic trainer data and text

Each file holds, for one class, what the WoW Forever client doesn't have:

* `costs` — spell id -> the lowest cost (copper) a Classic class trainer asks
  (`npc_trainer` / `npc_trainer_template`);
* `quests` — spells a Classic quest teaches (`quest_template` `RewSpell` /
  `RewSpellCast`);
* `books` — spells a Classic class book teaches (`item_template`: Dire Maul's
  Codex / Book / Tome, Ahn'Qiraj's rank tomes);
* `texts` — for ranks whose Forever tooltip can't be read in full, the Classic
  Era client's wording (wago.tools, `{era_branch}` {era_build}) filled with
  cmangos' 1.12 numbers (`spell_template`);
* `levels` — for ranks with no Forever spell level, cmangos' `SpellLevel`.

Trainers and quests are server-side, so Forever may differ; the page tags all
of it "Classic data". Everything is matched by spell id only.

From [cmangos classic-db](https://github.com/cmangos/classic-db) at commit
`{commit}`, licensed GPL-3.0 — see `LICENSE`. No cmangos code is used.

Generated by `python -m scripts.wow_spellbook.build`. Never hand-edit.
"""


def _read(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def downrank_families(path: Path = DOWNRANK_FILE) -> dict[tuple[str, str], str]:
    """(class, spell name) -> the downrank calculator's family id."""
    return {(f["classId"], f["name"]): f["id"] for f in _read(path)["families"]}


def tab_docs(class_id: str) -> list[dict[str, Any]]:
    return [{"id": line, "name": name} for line, name in CLASS_LINES[class_id].items()]


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the WoW Forever Spellbook's data.")
    parser.add_argument("--hotfix-cache", help="the Forever client's _forever_/Cache/ADB/enUS/DBCache.bin")
    args = parser.parse_args()

    forever = load_forever_tables(hotfix_cache_path(args.hotfix_cache), FOREVER_TABLES)
    tables = {name: forever.table(name) for name in FOREVER_TABLES}
    book = forever_book(tables)
    facts = SpellFacts.from_tables(tables)

    era = {"branch": WAGO_ERA_BRANCH, "build": WAGO_ERA_BUILD}
    era_spells = wago_table("Spell", **era)
    dump = read_dump(cmangos_dump(), {"spell_template", "npc_trainer", "npc_trainer_template", "quest_template", "item_template"})
    classic = classic_book(
        era_spells,
        wago_table("SpellName", **era),
        wago_table("SpellDuration", **era),
        wago_table("SpellRadius", **era),
        wago_table("SpellRange", **era),
        dump["spell_template"],
    )
    classic_level = {
        int(r["Id"]): int(r["SpellLevel"] or 0) for r in dump["spell_template"] if int(r["SpellLevel"] or 0) > 0
    }
    teaches = teaching_map(wago_table("SpellEffect", **era))
    costs = trainer_costs(dump["npc_trainer"] + dump["npc_trainer_template"], teaches)
    quests = quest_spells(dump["quest_template"], teaches)
    books = book_spells(dump["item_template"], teaches)
    learned = Learned(
        trainer=frozenset(costs),
        quest=frozenset(quests),
        book=frozenset(books),
        talent_of=talent_spells(tables["Talent"]),
    )

    classic_ids = frozenset(int(r["Id"]) for r in dump["spell_template"])
    line_class = {line: class_id for class_id, lines in CLASS_LINES.items() for line in lines}
    gaps = SpellGaps()
    spells = class_spells(
        tables["SkillLineAbility"], line_class, facts, classic_ids, learned, gaps,
    )
    changes = change_info(_read(CHANGED_SPELLS_FILE)["entries"])
    downrank = downrank_families()
    classic_source = (
        f"cmangos classic-db {CMANGOS_COMMIT[:12]} trainers, quests and numbers (GPL-3.0), Classic Era client "
        f"({WAGO_ERA_BRANCH} {WAGO_ERA_BUILD}) wording"
    )

    counts = FieldCounts()
    report: list[str] = []
    for class_id in CLASS_LINES:
        fill = ClassicFill()
        docs = [
            spell_doc(
                s,
                lambda spell: full_text(book, spell),
                lambda spell: full_text(classic, spell),
                classic_level, costs, quests, books, changes, downrank, fill, counts,
            )
            for s in spells
            if s.class_id == class_id
        ]
        write_lines(SPELLBOOK_DIR / f"{class_id}.json", {
            "source": forever.source(),
            "clientBuild": WAGO_BUILD,
            "classId": class_id,
            "tabs": tab_docs(class_id),
            "spells": docs,
        }, "spells")
        write_json(CLASSIC_DIR / f"{class_id}.json", fill.doc(classic_source, class_id))
        marked = sum(1 for d in docs if "changed" in d)
        report.append(f"  {class_id}: {len(docs)} spells, {sum(len(d['ranks']) for d in docs)} ranks, {marked} different from Classic")
    shutil.copyfile(CLASSIC_LICENSE, CLASSIC_DIR / "LICENSE")
    (CLASSIC_DIR / "README.md").write_text(
        CLASSIC_README.format(era_branch=WAGO_ERA_BRANCH, era_build=WAGO_ERA_BUILD, commit=CMANGOS_COMMIT),
        encoding="utf-8",
    )

    print(f"{len(spells)} spells, {counts.ranks} ranks")
    print("\n".join(report))
    print(
        f"text: {counts.text_classic} ranks from Classic, {counts.text_blank} blank; "
        f"level: {counts.level_classic} from Classic, {counts.level_blank} blank, {counts.level_talent} talent ranks left to the tree; "
        f"cost known for {counts.cost_known} ranks, quest-taught {counts.quest}, book-taught {counts.book}"
    )
    print(f"left out: {len(gaps.not_in_client)} not in the client, {len(gaps.untaught)} nothing teaches")


if __name__ == "__main__":
    main()
