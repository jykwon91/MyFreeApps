"""Build the WoW Forever item pages' data (``/wow-forever/items/:id``).

Usage (from ``apps/mygamingassistant/backend``)::

    python -m scripts.wow_item_pages.build --hotfix-cache "<Forever>/_forever_/Cache/ADB/enUS/DBCache.bin"

Run after the World Map, Professions and Items generators: it reads their
committed output (``items.json``, the crafting recipe JSON,
``classicQuests.json`` and ``classicDungeons.json``).

Writes two sets of shards (``id % SHARD_COUNT``; a page loads one of each),
kept apart because their licences differ:

* ``data/items/pages/NN.json`` — from the Forever client: the item's
  ``items.json`` row, its bind type and vendor price (ItemSparse, hotfixes
  included) and the recipes that make it (the crafting JSON).
* ``data/items/pages/classic/NN.json`` — cmangos classic-db (GPL-3.0, LICENSE
  + README next to it): vendors, quest rewards, open-world mob drops and
  dungeon / raid drops with the chance the server rolls, containers. Plus
  ``classic/unseen.json``: Classic gear no Forever client has shown yet, so a
  page for one can say so instead of "not found".

Game data © Blizzard Entertainment. Never hand-edit the output.
"""
from __future__ import annotations

import argparse
import json
import shutil
from collections import defaultdict
from pathlib import Path
from typing import Any

from scripts.wow_food.build import CLASSIC_LICENSE, WOW_DATA_DIR
from scripts.wow_food.recipe_sources import MOB_COLUMNS, VENDOR_COLUMNS, territory_of
from scripts.wow_gear.build import write_json
from scripts.wow_item_pages.drops import INSTANCE_COLUMNS
from scripts.wow_item_pages.facts import CRAFTED_COLUMNS, crafted_by, item_facts
from scripts.wow_item_pages.finder import ItemSourceFinder, instance_rows, quest_rows
from scripts.wow_item_pages.loot_chances import as_int
from scripts.wow_item_pages.shards import SHARD_COUNT, classic_shard, forever_shard, split
from scripts.wow_items.forever_items import hotfix_cache_path, load_forever_item_tables
from scripts.wow_world_map.map_art import WorldMapArt
from scripts.wow_world_map.sources import CMANGOS_COMMIT, WAGO_BUILD, cmangos_dump, wago_table
from scripts.wow_world_map.sql_dump import read_dump
from scripts.wow_world_map.zones import load_zones

ITEMS_PATH = WOW_DATA_DIR / "items" / "items.json"
PAGES_DIR = WOW_DATA_DIR / "items" / "pages"
CLASSIC_DIR = PAGES_DIR / "classic"
UNSEEN_PATH = CLASSIC_DIR / "unseen.json"
CRAFTING_DIR = WOW_DATA_DIR / "professions" / "crafting"
WORLD_MAP_CLASSIC = WOW_DATA_DIR / "worldMap" / "classic"
# Crafting JSON stems the Professions page opens with ``?p=`` (mining.json holds smelts, never gear).
CRAFTING_PROFESSIONS = ("alchemy", "blacksmithing", "enchanting", "engineering", "firstaid", "leatherworking", "tailoring")

FIRST_FOREVER_ITEM_ID = 100000
# Classic gear for unseen.json: uncommon or better weapons (class 2) and armour (class 4).
UNSEEN_MIN_QUALITY = 2
GEAR_CLASSES = frozenset({2, 4})

QUEST_COLUMNS = ["id", "title", "level", "side", "givers", "minLevel", "classes"]
QUEST_GIVER_COLUMNS = ["type", "entry", "name", "zone", "subzone", "x", "y", "faction"]
INSTANCE_INFO_COLUMNS = ["name", "type", "minLevel", "maxLevel", "requiredLevel", "zone", "x", "y"]

CLASSIC_README = """# Item pages — Classic sources

`NN.json` (shard = item id % {shards}) says how each item was got in Classic:
vendors (with limited stock), quest rewards, the open-world mobs that drop it
and the dungeon / raid mobs that drop it — with the chance the server rolls
(loot groups and reference tables followed; a reference shared by many
creatures is a random "world drop" and gets a level range instead of a mob
list) — and the clams, chests and nodes that hold it. `unseen.json` lists
Classic gear (uncommon or better weapons and armour) no WoW Forever client
has shown yet, so a page for one says so instead of "not found".

Derived from [cmangos classic-db](https://github.com/cmangos/classic-db) at
commit `{commit}` (`creature_template`, `creature`, `creature_loot_template`,
`reference_loot_template`, `npc_vendor`, `npc_vendor_template`,
`quest_template`, `item_template`, `item_loot_template`, `gameobject`,
`gameobject_template`, `gameobject_loot_template`), licensed GPL-3.0 — see
`LICENSE`. No cmangos code is used. Forever may differ: the page tags every
source "Classic data".

Generated by `backend/scripts/wow_item_pages/build.py`. Never hand-edit.
"""


def unseen_gear(item_rows: list[dict[str, Any]], forever_ids: set[int]) -> list[list[Any]]:
    """[[id, Classic name], ...] for Classic gear absent from every Forever item table we have."""
    return sorted(
        [as_int(r["entry"]), str(r["name"])]
        for r in item_rows
        if as_int(r["Quality"]) >= UNSEEN_MIN_QUALITY
        and as_int(r["class"]) in GEAR_CLASSES
        and as_int(r["entry"]) < FIRST_FOREVER_ITEM_ID
        and as_int(r["entry"]) not in forever_ids
    )


def _write_forever_shard(path: Path, header: dict[str, Any], shard: dict[str, Any]) -> None:
    """One item row and one fact per line, so a refresh diff names the items that changed."""
    def dumps(value: object) -> str:
        return json.dumps(value, ensure_ascii=False, separators=(",", ":"))

    head = ",".join(f"{dumps(k)}:{dumps(v)}" for k, v in {**header, "shard": shard["shard"], "shardCount": shard["shardCount"]}.items())
    rows = ",\n".join(dumps(r) for r in shard["items"])
    facts = ",\n".join(f"{dumps(k)}:{dumps(v)}" for k, v in shard["facts"].items())
    path.write_text(f"{{{head},\n\"items\":[\n{rows}\n],\n\"facts\":{{\n{facts}\n}}}}\n", encoding="utf-8")


def _load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _forever(items_doc: dict[str, Any], cache_path: Path, ids: list[list[int]]) -> set[int]:
    """Write the Forever shards; return every item id the Forever tables have."""
    wanted = {row[0] for row in items_doc["items"]}
    forever = load_forever_item_tables(cache_path)
    crafting = {stem: _load_json(CRAFTING_DIR / f"{stem}.json") for stem in CRAFTING_PROFESSIONS}
    crafted = crafted_by(crafting, wanted)
    facts = item_facts(forever.sparse, wanted)
    rows = {row[0]: row for row in items_doc["items"]}
    header = {
        "source": items_doc["source"],
        "clientBuild": items_doc["clientBuild"],
        "attribution": items_doc["attribution"],
        "columns": items_doc["columns"],
        "craftedColumns": CRAFTED_COLUMNS,
    }
    PAGES_DIR.mkdir(parents=True, exist_ok=True)
    for shard, shard_ids in enumerate(ids):
        _write_forever_shard(PAGES_DIR / f"{shard:02d}.json", header, forever_shard(shard, shard_ids, rows, facts, crafted))
    print(f"Forever: {len(crafted):,} crafted, {sum(1 for f in facts.values() if f.get('buy')):,} with a vendor price")
    return {as_int(r["ID"]) for r in forever.sparse}


def _classic(ids: list[list[int]], forever_ids: set[int]) -> dict[int, dict[str, object]]:
    """Write the Classic shards and unseen.json; return each item's sources."""
    tables = read_dump(cmangos_dump(), {"creature", "creature_loot_template", "reference_loot_template", "item_template"})
    instance_types = {as_int(r["ID"]): as_int(r["InstanceType"]) for r in wago_table("Map")}
    map_names = {as_int(r["ID"]): str(r["MapName_lang"]) for r in wago_table("Map")}
    encounters: dict[int, set[str]] = defaultdict(set)
    for row in wago_table("DungeonEncounter"):
        encounters[as_int(row["MapID"])].add(row["Name_lang"])
    wanted = {i for shard in ids for i in shard if i < FIRST_FOREVER_ITEM_ID}
    zone_entries, zone_bounds = load_zones()
    finder = ItemSourceFinder(zone_bounds, WorldMapArt(), tables, instance_types, encounters, wanted)
    sources = {i: finder.item_sources(i) for i in sorted(wanted)}
    quests = quest_rows(_load_json(WORLD_MAP_CLASSIC / "classicQuests.json"), {q for s in sources.values() for q in s.get("quests", [])})  # type: ignore[union-attr]
    for record in sources.values():
        if "quests" in record:
            record["quests"] = [q for q in record["quests"] if q in quests]  # type: ignore[union-attr]
            if not record["quests"]:
                del record["quests"]
    sources = {i: s for i, s in sources.items() if s}
    instances = instance_rows(_load_json(WORLD_MAP_CLASSIC / "classicDungeons.json"), map_names, instance_types, finder.instances)
    zone_names = {z.ui_map_id: z.name for z in zone_bounds}
    territory = territory_of(zone_names, zone_entries)
    header = {
        "source": {"repo": "cmangos/classic-db", "commit": CMANGOS_COMMIT, "license": "GPL-3.0-or-later"},
        "vendorColumns": VENDOR_COLUMNS,
        "mobColumns": MOB_COLUMNS,
        "instanceMobColumns": INSTANCE_COLUMNS,
        "instanceColumns": INSTANCE_INFO_COLUMNS,
        "questColumns": QUEST_COLUMNS,
        "questGiverColumns": QUEST_GIVER_COLUMNS,
    }
    CLASSIC_DIR.mkdir(parents=True, exist_ok=True)
    for shard, shard_ids in enumerate(ids):
        write_json(CLASSIC_DIR / f"{shard:02d}.json", {**header, **classic_shard(shard, shard_ids, sources, quests, instances, zone_names, territory)})
    unseen = unseen_gear(tables["item_template"], forever_ids)
    UNSEEN_PATH.write_text(json.dumps({
        "source": f"cmangos/classic-db@{CMANGOS_COMMIT}",
        "clientBuild": WAGO_BUILD,
        "items": unseen,
    }, ensure_ascii=False, separators=(",", ":")).replace("],[", "],\n[") + "\n", encoding="utf-8")
    shutil.copyfile(CLASSIC_LICENSE, CLASSIC_DIR / "LICENSE")
    (CLASSIC_DIR / "README.md").write_text(CLASSIC_README.format(commit=CMANGOS_COMMIT, shards=SHARD_COUNT), encoding="utf-8")
    print(f"Classic: {len(sources):,}/{len(wanted):,} items with a source, {len(quests):,} quests, "
          f"{len(instances):,} instances, {len(unseen):,} unseen gear")
    return sources


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the WoW Forever item pages' data.")
    parser.add_argument("--hotfix-cache", help="the Forever client's Cache/ADB/enUS/DBCache.bin")
    cache_path = hotfix_cache_path(parser.parse_args().hotfix_cache)
    items_doc = _load_json(ITEMS_PATH)
    ids = split(row[0] for row in items_doc["items"])
    print(f"{len(items_doc['items']):,} items in {SHARD_COUNT} shards; loading Forever tables...")
    forever_ids = _forever(items_doc, cache_path, ids)
    print("Reading cmangos classic-db...")
    _classic(ids, forever_ids)
    print(f"-> {PAGES_DIR}")


if __name__ == "__main__":
    main()
