QUESTS_DIR = WOW_DATA_DIR / "quests"
CLASSIC_DIR = QUESTS_DIR / "classic"
INDEX_PATH = QUESTS_DIR / "questIndex.json"
SEEN_PATH = QUESTS_DIR / "questSeen.json"
REWARD_ITEMS_PATH = QUESTS_DIR / "questRewardItems.json"
REWARD_ITEM_COLUMNS = ["name", "slot", "itemType"]
WORLD_MAP_CLASSIC = WOW_DATA_DIR / "worldMap" / "classic"
ITEMS_PATH = WOW_DATA_DIR / "items" / "items.json"
ZONES_FILE = WOW_DATA_DIR / "worldMap" / "zones.json"

SHARD_COUNT = 64
# Must match QUEST_SHARD_COUNT in frontend/src/games/wow-forever/data/quests/questsConfig.ts.
INDEX_COLUMNS = ["id", "name", "level", "minLevel", "side", "zoneId", "isNew"]
DUNGEON_KIND = "dungeon"

CLASSIC_README = """# Quest database — Classic quest data

Each ``NNN.json`` shard (0-padded, 00–63) contains Classic quest data for
the quests whose id mod {count} equals that number.

Columns match the dungeon quests format: ``questColumns``, ``giverColumns``,
``objectiveColumns``, ``targetColumns``. ``quests`` maps quest id → row
(same order as ``questColumns``); ``targets`` maps target key → [name, instance].

Only quests the WoW Forever client has (``QuestV2``) are kept. Reward items
are only items in ``items/items.json``.

Derived from [cmangos classic-db](https://github.com/cmangos/classic-db) at
commit `{commit}`, licensed GPL-3.0 — see `LICENSE`.
No cmangos code is used. Forever may differ: the page tags all of it "Classic data".

Generated by `backend/scripts/wow_quests/build.py`. Never hand-edit.
""".format(count=SHARD_COUNT, commit="{commit}")


def _dungeon_ids(dungeon_doc: dict[str, Any]) -> set[int]:
    """Instance map ids of the World Map's dungeon (not raid) entrances."""
    columns = dungeon_doc["columns"]
    at_instance = columns.index("instance")
    at_type = columns.index("type")
    return {int(r[at_instance]) for r in dungeon_doc["rows"] if r[at_type] == DUNGEON_KIND}


def quest_zone_map(world_quests: dict[str, Any]) -> dict[int, int]:
    """Quest id -> the World Map zone id of its first listed giver."""
    at_zone = WORLD_GIVER_COLUMNS.index("zone")
    at_quests = WORLD_GIVER_COLUMNS.index("quests")
    out: dict[int, int] = {}
    for row in world_quests.get("givers", []):
        zone = row[at_zone]
        if zone is None:
            continue
        for qid in row[at_quests]:
            out.setdefault(int(qid), int(zone))
    return out


def build_quest_index(
    forever_ids: set[int],
    new_ids: set[int],
    src_quests: dict[int, Any],
    keep: dict[int, str],
    cache: QuestCache,
    quest_zone: dict[int, int],
    zone_names: dict[int, str],
    seen_ids: set[int],
) -> dict[str, Any]:
    """The quest index: columnar, one row per quest."""
    rows = []
    for qid in sorted(forever_ids):
        if qid in src_quests:
            q = src_quests[qid]
            name: str | None = str(q["Title"]).strip() or None
            level = shown_level(as_int(q["QuestLevel"]), as_int(q["MinLevel"]))
            min_level = as_int(q["MinLevel"])
            side = keep.get(qid, "N")
        elif qid in cache.quests:
            cached = cache.quests[qid]
            name = cached.title.strip() or None
            level = shown_level(cached.level, cached.min_level)
            min_level = cached.min_level
            side = "N"
        else:
            name = None
            level = 1
            min_level = 1
            side = "N"
        zone_id = quest_zone.get(qid)
        is_new = qid in new_ids
        rows.append([qid, name, level, min_level, side, zone_id, is_new])

    # Zones that appear in the index, sorted by name
    used_zone_ids = sorted({r[5] for r in rows if r[5] is not None})
    zones = sorted(
        [[z, zone_names[z]] for z in used_zone_ids if z in zone_names],
        key=lambda z: z[1],
    )

    total = len(rows)
    named = sum(1 for r in rows if r[1] is not None)
    with_classic = sum(1 for r in rows if r[0] in src_quests)
    unnamed = total - named

    return {
        "source": {
            "clientTables": {
                "publisher": "Blizzard Entertainment (WoW Forever)",
                "via": "wago.tools DB2 export",
                "branch": WAGO_BRANCH,
                "build": WAGO_BUILD,
            },
            "classic": {"repo": "cmangos/classic-db", "commit": CMANGOS_COMMIT, "license": "GPL-3.0-or-later"},
        },
        "clientBuild": WAGO_BUILD,
        "columns": INDEX_COLUMNS,
        "zones": zones,
        "counts": {
            "total": total,
            "named": named,
            "withClassic": with_classic,
            "seenInGame": len(seen_ids),
            "unnamed": unnamed,
        },
        "quests": rows,
    }


def build_shards(
    forever_ids: set[int],
    src: Any,  # QuestSources
    keep: dict[int, str],
) -> dict[int, dict[str, Any]]:
    """64 shards of Classic quest data, keyed by id % SHARD_COUNT."""
    before = predecessors(src.quests)
    rows: dict[int, QuestRow] = {}
    for qid in sorted(forever_ids & set(src.quests) & set(keep)):
        rows[qid] = quest_row(qid, keep[qid], chain_before(qid, before, keep), src)

    shard_quests: dict[int, dict[int, QuestRow]] = defaultdict(dict)
    for qid, row in rows.items():
        shard_quests[qid % SHARD_COUNT][qid] = row

    # Per-shard targets (only what that shard's quests reference)
    result: dict[int, dict[str, Any]] = {}
    for n in range(SHARD_COUNT):
        shard_rows = shard_quests.get(n, {})
        shard_keys = {f"{k}:{e}" for r in shard_rows.values() for k, e, _ in r.objectives}
        shard_keys |= {k for r in shard_rows.values() for k in r.enders}
        result[n] = {
            "quests": {str(r.quest_id): r.as_json() for r in sorted(shard_rows.values(), key=lambda r: r.quest_id)},
            "targets": {
                k: [src.names[k], src.inside.get(k)]
                for k in sorted(shard_keys)
                if k in src.names
            },
        }
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the WoW Forever quest database.")
    parser.add_argument("--quest-cache", help="the Forever client's Cache/WDB/enUS/questcache.wdb")
    cache, seen_on = read_quest_cache(quest_cache_path(parser.parse_args().quest_cache))

    items_doc = json.loads(ITEMS_PATH.read_text(encoding="utf-8"))
    forever_items: set[int] = {int(row[0]) for row in items_doc["items"]}
    world_quests = json.loads((WORLD_MAP_CLASSIC / "classicQuests.json").read_text(encoding="utf-8"))
    zones_data = json.loads(ZONES_FILE.read_text(encoding="utf-8"))
    zone_names: dict[int, str] = {
        z["id"]: z["name"] for z in zones_data["zones"] if z.get("kind") in ("zone", "city")
    }
    dungeon_doc = json.loads((WORLD_MAP_CLASSIC / "classicDungeons.json").read_text(encoding="utf-8"))
    dungeons = _dungeon_ids(dungeon_doc)

    print("Reading cmangos classic-db...")
    tables = read_dump(
        cmangos_dump(),
        {
            "creature", "creature_template", "creature_loot_template", "reference_loot_template",
            "quest_template", "creature_questrelation", "gameobject_questrelation",
            "creature_involvedrelation", "gameobject_involvedrelation",
            "gameobject", "gameobject_template", "gameobject_loot_template", "item_template",
        },
    )
    src = quest_sources(tables, world_quests, dungeons, forever_items)

    print("Loading QuestV2 from wago.tools...")
    era = {"branch": WAGO_ERA_BRANCH, "build": WAGO_ERA_BUILD}
    forever_ids = {int(r["ID"]) for r in wago_table("QuestV2", hotfixes=True)}
    era_ids = {int(r["ID"]) for r in wago_table("QuestV2", **era, hotfixes=True)}
    new_ids = forever_ids - era_ids

    keep = forever_quest_sides(dict(src.quests), forever_ids)
    quest_zone = quest_zone_map(world_quests)
    seen_ids = {qid for qid in sorted(forever_ids) if qid in cache.quests and qid not in cache.unreadable}

    print(f"Building quest index for {len(forever_ids)} quests...")
    index = build_quest_index(forever_ids, new_ids, dict(src.quests), keep, cache, quest_zone, zone_names, seen_ids)
    write_json(INDEX_PATH, index)

    print(f"Building {SHARD_COUNT} classic shards...")
    shards = build_shards(forever_ids, src, keep)
    classic_source = {"repo": "cmangos/classic-db", "commit": CMANGOS_COMMIT, "license": "GPL-3.0-or-later"}
    CLASSIC_DIR.mkdir(parents=True, exist_ok=True)
    for n, shard in sorted(shards.items()):
        write_json(
            CLASSIC_DIR / f"{n:02d}.json",
            {
                "source": classic_source,
                "questColumns": QUEST_COLUMNS,
                "giverColumns": GIVER_COLUMNS,
                "objectiveColumns": OBJECTIVE_COLUMNS,
                "targetColumns": TARGET_COLUMNS,
                **shard,
            },
        )
    shutil.copyfile(CLASSIC_LICENSE, CLASSIC_DIR / "LICENSE")
    (CLASSIC_DIR / "README.md").write_text(
        CLASSIC_README.format(commit=CMANGOS_COMMIT), encoding="utf-8"
    )

    seen = {}
    for qid in sorted(seen_ids):
        s = seen_row(cache.quests[qid], src)
        seen[str(qid)] = s.as_json()
    write_json(SEEN_PATH, {
        "source": "The WoW Forever client's quest cache (Cache/WDB/enUS/questcache.wdb) on the operator's machine",
        "clientBuild": cache.build,
        "seenOn": seen_on,
        "attribution": "Game data from the WoW Forever client. © Blizzard Entertainment.",
        "columns": SEEN_COLUMNS,
        "quests": seen,
    })

    # Reward items: name + slot for every item any quest rewards
    reward_item_ids: set[int] = set()
    for shard in shards.values():
        for row in shard["quests"].values():
            q_col = QUEST_COLUMNS
            at_rew = q_col.index("rewards")
            at_cho = q_col.index("choices")
            reward_item_ids |= {int(item) for item, _ in row[at_rew] + row[at_cho]}
    for qid in sorted(seen_ids):
        s = seen_row(cache.quests[qid], src)
        reward_item_ids |= {item for item, _ in (*s.rewards, *s.choices)}

    items_by_id = {int(row[0]): row for row in items_doc["items"]}
    items_columns = items_doc["columns"]
    at_name = items_columns.index("name")
    at_slot = items_columns.index("slot")
    at_type = items_columns.index("itemType")
    reward_items = {
        str(item_id): [items_by_id[item_id][at_name], items_by_id[item_id][at_slot], items_by_id[item_id][at_type]]
        for item_id in sorted(reward_item_ids)
        if item_id in items_by_id
    }
    write_json(REWARD_ITEMS_PATH, {
        "source": items_doc["source"],
        "clientBuild": items_doc["clientBuild"],
        "columns": REWARD_ITEM_COLUMNS,
        "items": reward_items,
    })

    counts = index["counts"]
    print(
        f"wrote {INDEX_PATH.name}: {counts['total']} quests "
        f"({counts['named']} named, {counts['withClassic']} with Classic data, "
        f"{counts['seenInGame']} seen in game, {counts['unnamed']} unnamed) -> {QUESTS_DIR}"
    )
    print(f"wrote {len(shards)} classic shards to {CLASSIC_DIR}")
    print(f"wrote {SEEN_PATH.name}: {len(seen)} seen quests (build {cache.build}, {seen_on})")
    print(f"wrote {REWARD_ITEMS_PATH.name}: {len(reward_items)} reward items")


if __name__ == "__main__":
    main()
