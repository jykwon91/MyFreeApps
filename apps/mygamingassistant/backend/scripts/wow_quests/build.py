"""Build the WoW Forever quest database pages (``/wow-forever/quests``, ``/wow-forever/quests/:id``).

Usage (from ``apps/mygamingassistant/backend``)::

    python -m scripts.wow_quests.build [--quest-cache <questcache.wdb>]

Generalises the dungeon-quest pipeline to ALL quests the WoW Forever client
has (``QuestV2``). Reads the World Map, Items and Dungeon builds' committed
output plus the operator's ``questcache.wdb``; never re-reads the client files
directly.

Writes:

* ``data/quests/questIndex.json`` — columnar index of every quest in
  ``QuestV2``: name (or null), level, side, zone and new-in-Forever flag.
* ``data/quests/questSeen.json`` — the Forever client's quest cache: title,
  levels, objectives and rewards for the quests the operator has seen.
* ``data/quests/classic/NNN.json`` — 64 cmangos GPL shards (``id % 64``):
  full quest data (givers, chain, objectives, rewards) for every Classic quest
  the Forever client has.
* ``data/quests/classic/LICENSE`` + ``README.md`` — GPL-3.0 attribution.
* ``data/quests/questRewardItems.json`` — name + slot of every quest reward item
  (from ``items.json``) so the detail page can show item names without loading
  the full item browser.

Game data © Blizzard Entertainment. Never hand-edit the output.
"""
