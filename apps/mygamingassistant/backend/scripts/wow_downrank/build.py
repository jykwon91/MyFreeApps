"""Build the WoW Forever downrank calculator's data (``/wow-forever/downrank``).

Usage (from ``apps/mygamingassistant/backend``)::

    python -m scripts.wow_downrank.build [--hotfix-cache <DBCache.bin>]

For each spell family in ``families.py``, every rank's learn level, max
level, mana cost, cast time, base amount (base points, per-level gain,
spread) and spell-power coefficient, from the Forever client: Spell,
SpellName, SpellEffect, SpellMisc, SpellDuration, SpellCastTimes,
SpellLevels, SpellPower and SkillLineAbility, with the hotfix layers the
item build uses (``--hotfix-cache``, else ``WOW_FOREVER_HOTFIX_CACHE``, else
the default install path; the run stops without it). Run after
``scripts.wow_changes.build`` — a family Forever changed links to that feed.

Writes:

* ``data/downrank/spells.json`` — the families and their Forever ranks.
* ``data/downrank/classic/ranks.json`` — ranks Forever's client doesn't have
  in full, from Classic: the Classic Era client's cast times and durations
  with cmangos classic-db's 1.12 numbers (GPL-3.0, LICENSE + README next to
  it) and the Classic formula's coefficient. The page tags them Classic data.

Game data © Blizzard Entertainment. Never hand-edit the output.
"""
from __future__ import annotations

import argparse
import json
import shutil
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from scripts.wow_downrank.families import FAMILIES, Family
from scripts.wow_downrank.ranks import (
    FROM_CLASSIC,
    ClientSpells,
    Rank,
    RankGaps,
    classic_rank,
    family_spells,
    pick_client_rank,
    rank_docs,
)
from scripts.wow_food.build import CLASSIC_LICENSE, WOW_DATA_DIR
from scripts.wow_items.forever_items import hotfix_cache_path, load_forever_tables
from scripts.wow_macros.build import CLASS_LINES
from scripts.wow_world_map.sources import (
    CMANGOS_COMMIT,
    WAGO_BUILD,
    WAGO_ERA_BRANCH,
    WAGO_ERA_BUILD,
    cmangos_dump,
    wago_table,
)
from scripts.wow_world_map.sql_dump import SqlValue, read_dump

DOWNRANK_DIR = WOW_DATA_DIR / "downrank"
CLASSIC_DIR = DOWNRANK_DIR / "classic"
CHANGED_SPELLS_FILE = WOW_DATA_DIR / "changes" / "classic" / "spells.json"
FOREVER_TABLES = (
    "Spell",
    "SpellName",
    "SpellEffect",
    "SpellMisc",
    "SpellDuration",
    "SpellCastTimes",
    "SpellLevels",
    "SpellPower",
    "SkillLineAbility",
)

CLASSIC_README = """# Downrank calculator — Classic ranks

`ranks.json` holds, per spell family, the ranks the WoW Forever client
doesn't have in full yet. The calculator shows them with a "Classic data"
badge.

Each rank's level, max level, mana cost and amounts are the 1.12 numbers from
[cmangos classic-db](https://github.com/cmangos/classic-db) at commit
`{commit}` (`spell_template`), licensed GPL-3.0 — see `LICENSE`; cast times
and durations are the Classic Era client's (wago.tools, `{era_branch}`
{era_build}: `SpellCastTimes`, `SpellDuration`), and the spell-power
coefficient is the Classic formula's.

Generated by `python -m scripts.wow_downrank.build`. Never hand-edit.
"""


LINE_BREAK = ",\n"


def _compact(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def write_families(path: Path, doc: Mapping[str, Any]) -> None:
    """The JSON with one family header and one rank per line, so a refresh diff names the ranks that moved."""
    parts = []
    for key, value in doc.items():
        if key != "families":
            parts.append(f"{json.dumps(key)}:{_compact(value)}")
            continue
        families = []
        for family in value:
            head = _compact({k: v for k, v in family.items() if k != "ranks"})[:-1]
            ranks = LINE_BREAK.join(_compact(r) for r in family["ranks"])
            families.append(f'{head},"ranks":[\n{ranks}\n]}}')
        parts.append('"families":[\n' + LINE_BREAK.join(families) + "\n]")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("{" + LINE_BREAK.join(parts) + "}\n", encoding="utf-8")


def changed_families(path: Path = CHANGED_SPELLS_FILE) -> set[str]:
    """``spell:<class>:<name>`` keys of the class spells the Changes vs Classic feed lists as changed."""
    doc = json.loads(path.read_text(encoding="utf-8"))
    return {e["key"] for e in doc["entries"] if e["kind"] == "changed"}


def family_ranks(
    family: Family,
    forever: ClientSpells,
    forever_abilities: list[dict[str, str]],
    era_abilities: list[dict[str, str]],
    era_names: Mapping[int, str],
    era_subtexts: Mapping[int, str],
    spell_template: Mapping[int, Mapping[str, SqlValue]],
    era_cast_times: Mapping[int, int],
    era_durations: Mapping[int, int],
    gaps: RankGaps,
) -> list[Rank]:
    """The family's ranks: Forever's where its client has them in full, else Classic's."""
    lines = CLASS_LINES[family.class_id].keys()
    forever_ids = family_spells(family, forever_abilities, lines, forever.names, forever.subtexts)
    era_ids = family_spells(family, era_abilities, lines, era_names, era_subtexts)
    ranks: list[Rank] = []
    for number in sorted(forever_ids.keys() | era_ids.keys()):
        rank = pick_client_rank(forever, family, number, forever_ids.get(number, []))
        if rank is None:
            classic = (
                classic_rank(spell_template[s], number, family.kind, era_cast_times, era_durations)
                for s in era_ids.get(number, [])
                if s in spell_template
            )
            rank = next((r for r in classic if r is not None), None)
            if rank is not None:
                gaps.from_classic.append(f"{family.id} Rank {number}")
        if rank is None:
            gaps.missing.append(f"{family.id} Rank {number}")
        else:
            ranks.append(rank)
    return ranks


def family_doc(family: Family, ranks: list[Rank], docs: list[dict[str, Any]], icons: Mapping[int, int], changed: set[str]) -> dict[str, Any]:
    icon = next((icons[r.spell] for r in reversed(ranks) if r.spell in icons), 0)
    return {
        "id": family.id,
        "classId": family.class_id,
        "name": family.name,
        "kind": family.kind,
        "targets": ranks[0].targets,
        "icon": icon,
        "changedInForever": f"spell:{family.class_id}:{family.name}" in changed,
        "ranks": [d for d in docs if d["from"] != FROM_CLASSIC],
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the WoW Forever downrank calculator's data.")
    parser.add_argument("--hotfix-cache", help="the Forever client's _forever_/Cache/ADB/enUS/DBCache.bin")
    args = parser.parse_args()

    forever_tables = load_forever_tables(hotfix_cache_path(args.hotfix_cache), FOREVER_TABLES)
    forever = ClientSpells.from_tables({name: forever_tables.table(name) for name in FOREVER_TABLES})
    era = {"branch": WAGO_ERA_BRANCH, "build": WAGO_ERA_BUILD}
    era_names = {int(r["ID"]): r["Name_lang"] for r in wago_table("SpellName", **era)}
    era_subtexts = {int(r["ID"]): r.get("NameSubtext_lang", "") for r in wago_table("Spell", **era)}
    era_cast_times = {int(r["ID"]): int(r["Base"]) for r in wago_table("SpellCastTimes", **era)}
    era_durations = {int(r["ID"]): int(r["Duration"]) for r in wago_table("SpellDuration", **era)}
    spell_template = {int(r["Id"]): r for r in read_dump(cmangos_dump(), {"spell_template"})["spell_template"]}
    changed = changed_families()

    gaps = RankGaps()
    families: list[dict[str, Any]] = []
    classic_ranks: list[dict[str, Any]] = []
    for family in FAMILIES:
        ranks = family_ranks(
            family, forever, forever_tables.table("SkillLineAbility"), wago_table("SkillLineAbility", **era),
            era_names, era_subtexts, spell_template, era_cast_times, era_durations, gaps,
        )
        if not ranks:
            raise SystemExit(f"{family.id}: no ranks in either client")
        docs = rank_docs(ranks)
        families.append(family_doc(family, ranks, docs, forever.icons, changed))
        fallback = [d for d in docs if d["from"] == FROM_CLASSIC]
        if fallback:
            classic_ranks.append({"id": family.id, "ranks": fallback})

    write_families(DOWNRANK_DIR / "spells.json", {
        "source": forever_tables.source(),
        "clientBuild": WAGO_BUILD,
        "families": families,
    })
    write_families(CLASSIC_DIR / "ranks.json", {
        "source": (
            f"cmangos classic-db {CMANGOS_COMMIT[:12]} numbers (GPL-3.0), Classic Era client "
            f"({WAGO_ERA_BRANCH} {WAGO_ERA_BUILD}) cast times and durations"
        ),
        "families": classic_ranks,
    })
    shutil.copyfile(CLASSIC_LICENSE, CLASSIC_DIR / "LICENSE")
    (CLASSIC_DIR / "README.md").write_text(
        CLASSIC_README.format(commit=CMANGOS_COMMIT, era_branch=WAGO_ERA_BRANCH, era_build=WAGO_ERA_BUILD),
        encoding="utf-8",
    )

    total = sum(len(f["ranks"]) for f in families)
    print(f"{len(families)} spell families, {total} Forever ranks, {len(gaps.from_classic)} ranks from Classic")
    if gaps.from_classic:
        print(f"  from Classic: {', '.join(gaps.from_classic)}")
    if gaps.missing:
        print(f"  in neither client in full (left out): {', '.join(gaps.missing)}")


if __name__ == "__main__":
    main()
