"""Build the WoW Forever Item Compare item list.

Usage (from ``apps/mygamingassistant/backend``)::

    python -m scripts.wow_items.build

Writes ``frontend/src/games/wow-forever/data/items/items.json`` — every
uncommon-or-better piece of gear in the Forever client (the build pinned in
``scripts/wow_world_map/sources.py``) that has stats, with the stat amounts,
armor and weapon damage worked out from the client's budget tables
(``formula.py``). Caster weapons' damage can't be reproduced from the client,
so it is left out (``damageUnknown``) for the player to type in.

``data/items/classic/randomSuffixItems.json`` lists the items whose stats come
from a random "of the …" suffix. The Forever client ships no suffix tables, so
that list is cmangos classic-db (GPL-3.0, LICENSE + README next to it).

Item data from the WoW Forever client via wago.tools. Game data © Blizzard
Entertainment. Never hand-edit the output.
"""
from __future__ import annotations

import json
import re
import shutil
from pathlib import Path
from typing import Any

from scripts.wow_food.build import CLASSIC_LICENSE, WOW_DATA_DIR
from scripts.wow_items.client_ids import (
    BONUS_ARMOR_STAT_ID,
    CLASS_ID_BY_BIT,
    DAMAGE_TABLES,
    INVENTORY_TYPE_BACK,
    ITEM_CLASS_ARMOR,
    ITEM_CLASS_WEAPON,
    QUALITY_BY_ID,
    SLOT_BY_INVENTORY_TYPE,
    STAT_KEY_BY_CLIENT_ID,
    UNNAMED_SUBCLASSES,
)
from scripts.wow_items.formula import (
    BudgetTables,
    Row,
    armor_value,
    damage_table,
    stat_lines,
    stat_values,
    weapon_damage,
)
from scripts.wow_world_map.sources import CMANGOS_COMMIT, WAGO_BRANCH, WAGO_BUILD, cmangos_dump, wago_table
from scripts.wow_world_map.sql_dump import read_dump

DATA_DIR = WOW_DATA_DIR / "items"
OUT_PATH = DATA_DIR / "items.json"
CLASSIC_DIR = DATA_DIR / "classic"
SUFFIX_PATH = CLASSIC_DIR / "randomSuffixItems.json"

ATTRIBUTION = "Item data from the WoW Forever client via wago.tools. Game data © Blizzard Entertainment."
MIN_QUALITY = 2  # uncommon
SKIPPED_SLOTS = frozenset({"shirt", "tabard"})
# Developer, placeholder and NPC-only items the client still carries.
JUNK_NAME = re.compile(
    r"^\d+ |^Monster - |\[PH\]|\bPH\b|^\[TMP\]|^Deprecated |\bDEPRECATED\b|\bUNUSED\b|^OLD |^NPC |^QA"
    r"|(?i:\btest\b)"
)
ALL_CLASSES_MASK = sum(CLASS_ID_BY_BIT)

COLUMNS = [
    "id", "name", "quality", "slot", "itemType", "itemLevel", "requiredLevel",
    "armor", "weapon", "stats", "classes", "damageUnknown", "otherEffects",
]

CLASSIC_README = """# Item Compare — random-suffix items (Classic)

`randomSuffixItems.json` lists the items whose stats come from a random
"of the Bear / of the Eagle …" suffix rolled when the item drops, so the
item list can't give their numbers — the page asks for them from the
player's tooltip instead. The Forever client ships no suffix tables, so the
list comes from [cmangos classic-db](https://github.com/cmangos/classic-db)
at commit `{commit}` (`item_template.RandomProperty`), licensed GPL-3.0 —
see `LICENSE`. No cmangos code is used. Forever may differ.

Generated by `backend/scripts/wow_items/build.py`. Never hand-edit.
"""


def _int(value: str | None) -> int:
    try:
        return int(float(value or 0))
    except ValueError:
        return 0


def _by(rows: list[Row], key: str) -> dict[int, Row]:
    return {_int(r[key]): r for r in rows}


def load_tables() -> BudgetTables:
    return BudgetTables(
        rand_prop_points=_by(wago_table("RandPropPoints"), "ID"),
        armor_quality=_by(wago_table("ItemArmorQuality"), "ID"),
        armor_shield=_by(wago_table("ItemArmorShield"), "ItemLevel"),
        armor_total=_by(wago_table("ItemArmorTotal"), "ItemLevel"),
        armor_location=_by(wago_table("ArmorLocation"), "ID"),
        damage={name: _by(wago_table(name), "ItemLevel") for name in DAMAGE_TABLES},
    )


def load_subclass_names() -> dict[tuple[int, int], str]:
    return {
        (_int(r["ClassID"]), _int(r["SubClassID"])): r["DisplayName_lang"]
        for r in wago_table("ItemSubClass")
        if r.get("DisplayName_lang")
    }


def random_suffix_ids() -> set[int]:
    """Classic items whose stats come from a random suffix (cmangos ``RandomProperty``)."""
    rows = read_dump(cmangos_dump(), {"item_template"})["item_template"]
    return {_int(r["entry"]) for r in rows if _int(r.get("RandomProperty")) > 0}


def class_list(sparse: Row) -> list[str] | None:
    """Classes the item is restricted to; None when every class may equip it."""
    mask = _int(sparse.get("AllowableClass"))
    if mask <= 0 or mask & ALL_CLASSES_MASK == ALL_CLASSES_MASK:
        return None
    return [class_id for bit, class_id in CLASS_ID_BY_BIT.items() if mask & bit]


def item_type(sparse: Row, item: Row, subclass_names: dict[tuple[int, int], str]) -> str | None:
    class_id = _int(item["ClassID"])
    if class_id not in (ITEM_CLASS_ARMOR, ITEM_CLASS_WEAPON):
        return None
    if class_id == ITEM_CLASS_ARMOR and _int(sparse["InventoryType"]) == INVENTORY_TYPE_BACK:
        return None  # cloaks are cloth in the data but the tooltip names no type
    name = subclass_names.get((class_id, _int(item["SubclassID"])))
    return None if name in UNNAMED_SUBCLASSES else name


def map_stats(values: dict[int, int]) -> tuple[dict[str, int], int]:
    """Client stat amounts → compare-page stat keys, plus how many stats have no key."""
    stats: dict[str, int] = {}
    other = 0
    for stat_id, amount in values.items():
        key = STAT_KEY_BY_CLIENT_ID.get(stat_id)
        if key is None:
            other += 1
        else:
            stats[key] = stats.get(key, 0) + amount
    return dict(sorted(stats.items())), other


def build_record(
    sparse: Row,
    item: Row,
    tables: BudgetTables,
    subclass_names: dict[tuple[int, int], str],
    suffix_ids: set[int],
) -> list[Any] | None:
    """One row of ``items.json`` (``COLUMNS`` order); None when the item isn't compare-page gear."""
    item_id = _int(sparse["ID"])
    name = (sparse.get("Display_lang") or "").strip()
    quality = _int(sparse["OverallQualityID"])
    slot = SLOT_BY_INVENTORY_TYPE.get(_int(sparse["InventoryType"]))
    if not name or JUNK_NAME.search(name) or quality < MIN_QUALITY or slot is None or slot in SKIPPED_SLOTS:
        return None
    values = stat_values(sparse, tables)
    has_lines = any(s != BONUS_ARMOR_STAT_ID for s, _ in stat_lines(sparse))
    is_suffix = item_id in suffix_ids
    if values is None or not (has_lines or is_suffix):
        return None
    stats, other = map_stats(values)
    damage = weapon_damage(sparse, item, tables)
    damage_unknown = damage_table(sparse, item) is not None and damage is None
    weapon = None if damage is None else [damage.min_damage, damage.max_damage, damage.speed]
    return [
        item_id,
        name,
        QUALITY_BY_ID[quality],
        slot,
        item_type(sparse, item, subclass_names),
        _int(sparse["ItemLevel"]),
        _int(sparse.get("RequiredLevel")),
        armor_value(sparse, item, tables),
        weapon,
        stats,
        class_list(sparse),
        1 if damage_unknown else 0,
        other,
    ]


def build_items(
    sparse_rows: list[Row],
    item_rows: dict[int, Row],
    tables: BudgetTables,
    subclass_names: dict[tuple[int, int], str],
    suffix_ids: set[int],
) -> list[list[Any]]:
    records = []
    for sparse in sparse_rows:
        item = item_rows.get(_int(sparse["ID"]))
        if item is None:
            continue
        record = build_record(sparse, item, tables, subclass_names, suffix_ids)
        if record is not None:
            records.append(record)
    return sorted(records, key=lambda r: r[0])


def write_rows(path: Path, header: dict[str, Any], key: str, rows: list[Any]) -> None:
    """JSON with one row per line, so a refresh diff shows exactly which items changed."""
    path.parent.mkdir(parents=True, exist_ok=True)
    head = json.dumps(header, ensure_ascii=False, separators=(",", ":"))[:-1]
    body = ",\n".join(json.dumps(r, ensure_ascii=False, separators=(",", ":")) for r in rows)
    path.write_text(f'{head},"{key}":[\n{body}\n]}}\n', encoding="utf-8")


def main() -> None:
    print(f"Loading item tables from wago.tools ({WAGO_BRANCH} {WAGO_BUILD})...")
    tables = load_tables()
    item_rows = _by(wago_table("Item"), "ID")
    suffix_ids = random_suffix_ids()
    records = build_items(wago_table("ItemSparse"), item_rows, tables, load_subclass_names(), suffix_ids)
    write_rows(OUT_PATH, {
        "source": f"wago.tools DB2 {WAGO_BRANCH} {WAGO_BUILD}",
        "clientBuild": WAGO_BUILD,
        "attribution": ATTRIBUTION,
        "columns": COLUMNS,
    }, "items", records)

    included = {r[0] for r in records}
    suffix = sorted(included & suffix_ids)
    CLASSIC_DIR.mkdir(parents=True, exist_ok=True)
    SUFFIX_PATH.write_text(
        json.dumps({"source": f"cmangos/classic-db@{CMANGOS_COMMIT}", "ids": suffix}, separators=(",", ":")) + "\n",
        encoding="utf-8",
    )
    shutil.copyfile(CLASSIC_LICENSE, CLASSIC_DIR / "LICENSE")
    (CLASSIC_DIR / "README.md").write_text(CLASSIC_README.format(commit=CMANGOS_COMMIT), encoding="utf-8")
    no_damage = sum(1 for r in records if r[COLUMNS.index("damageUnknown")])
    print(f"{len(records):,} items ({len(suffix)} random-suffix, {no_damage} caster weapons without damage) -> {OUT_PATH}")


if __name__ == "__main__":
    main()
