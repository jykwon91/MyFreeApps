"""The MGA Drops addon's ``Data.lua``, written from the creature lists.

Layout (read by ``frontend/addon/MGADrops/Core.lua``)::

    MGADropsData = {
      build = "<Forever client build>", classicDb = "<cmangos commit>",
      items = { [id] = {name, quality}, ... },
      lists = { {w = <world-drop percent>, {item, percent, note, hordePercent}, ...}, ... },
      npcs  = { [npc id] = {name, min level, max level, list index}, ... },
    }

``percent`` is an Alliance player's; ``hordePercent`` is only there when a
Horde player's differs (0 = Alliance only). ``note`` (nil for none) is what
the drop needs: "quest", a profession, "holiday", "buff", "item", "special".
"""
from __future__ import annotations

from collections.abc import Mapping

from scripts.wow_mob_drops.mob_drops import Creature, Drop, LootList


def lua_string(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "")
    return f'"{escaped}"'


def lua_number(value: float) -> str:
    return str(int(value)) if float(value).is_integer() else repr(float(value))


def drop_lua(drop: Drop) -> str:
    parts = [str(drop.item), lua_number(drop.alliance)]
    if drop.note is not None or drop.horde != drop.alliance:
        parts.append(lua_string(drop.note) if drop.note is not None else "nil")
    if drop.horde != drop.alliance:
        parts.append(lua_number(drop.horde))
    return "{" + ", ".join(parts) + "}"


def list_lua(loot: LootList) -> str:
    parts = ([f"w = {lua_number(loot.world)}"] if loot.world else []) + [drop_lua(d) for d in loot.drops]
    return "{" + ", ".join(parts) + "}"


def data_lua(
    creatures: list[Creature],
    lists: list[LootList],
    items: Mapping[int, tuple[str, int]],
    *,
    build: str,
    classic_db: str,
) -> str:
    """The whole file. Only items some list names are written; Lua list indexes start at 1."""
    used = sorted({d.item for loot in lists for d in loot.drops})
    lines = [
        "-- Generated by `python -m scripts.wow_mob_drops.build` (apps/mygamingassistant/backend). Do not edit.",
        "-- Drop chances are Classic's: derived from cmangos classic-db (github.com/cmangos/classic-db), GPL-3.0, see LICENSE.",
        "-- WoW Forever may differ. Item names and quality from the WoW Forever client. Game data (c) Blizzard Entertainment.",
        "MGADropsData = {",
        f"  build = {lua_string(build)}, classicDb = {lua_string(classic_db)},",
        "  items = {",
    ]
    lines += [f"    [{i}] = {{{lua_string(items[i][0])}, {items[i][1]}}}," for i in used]
    lines += ["  },", "  lists = {"]
    lines += [f"    {list_lua(loot)}," for loot in lists]
    lines += ["  },", "  npcs = {"]
    lines += [
        f"    [{c.npc}] = {{{lua_string(c.name)}, {c.min_level}, {c.max_level}, {c.loot + 1}}},"
        for c in creatures
    ]
    lines += ["  },", "}", ""]
    return "\n".join(lines)
