"""Build the WoW Forever races page's data (``/wow-forever/races``).

Usage (from ``apps/mygamingassistant/backend``)::

    python -m scripts.wow_races.build [--hotfix-cache <DBCache.bin>]

Every race, class pair and racial comes from the Forever client (wago.tools
``wowf``; the spell tables with the hotfix layers the item build uses —
``--hotfix-cache``, else ``WOW_FOREVER_HOTFIX_CACHE``, else the default
install path; the run stops without it): ``ChrRaces``, ``CharBaseInfo``,
``SkillLine`` / ``SkillRaceClassInfo`` / ``SkillLineAbility`` for the racial
skill lines, and ``Spell`` / ``SpellName`` / ``SpellEffect`` / ``SpellMisc``
for each racial's tooltip, icon and active/passive. Each is compared with the
Classic Era client the way the Changes vs Classic feed compares class spells.

Writes ``data/races/``:

* ``races.json`` — the Forever side: races, faction, classes (and which pairs
  are new), each racial's status, icon and Forever text; removed racials are
  named from the Classic Era client.
* ``classic/racials.json`` — Classic's side: starting zones (cmangos
  ``playercreateinfo``) and the Classic text of every changed or removed
  racial, the Classic Era client's wording filled with cmangos classic-db's
  1.12 numbers (GPL-3.0, LICENSE + README next to it).

Game data © Blizzard Entertainment. Never hand-edit the output.
"""
