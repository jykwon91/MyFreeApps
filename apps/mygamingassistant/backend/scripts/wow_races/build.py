RACES_DIR = WOW_DATA_DIR / "races"
CLASSIC_DIR = RACES_DIR / "classic"
ZONES_PATH = WOW_DATA_DIR / "worldMap" / "zones.json"
FOREVER_TABLES = (
    "Spell",
    "SpellName",
    "SpellEffect",
    "SpellMisc",
    "SpellAuraOptions",
    "SpellDuration",
    "SpellRadius",
    "SkillLineAbility",
)
ATTRIBUTION = "From the WoW Forever and Classic Era clients via wago.tools. Game data © Blizzard Entertainment."

CLASSIC_README = """# Races — Classic racial text and starting zones

`racials.json` holds, per race, the Classic side of the races page:

* `startZone` — where a new character of that race starts in Classic, from
  [cmangos classic-db](https://github.com/cmangos/classic-db) at commit
  `{commit}` (`playercreateinfo`). The page tags it "Classic data".
* `racials` — the Classic text of every racial Forever changed or removed:
  the Classic Era client's own tooltip wording (wago.tools, `{era_branch}`
  {era_build}: `Spell`, `SpellName`, `SpellDuration`, `SpellRadius`) filled
  with cmangos' 1.12 numbers (`spell_template`).

cmangos classic-db is licensed GPL-3.0 — see `LICENSE`. No cmangos code is used.

Generated by `python -m scripts.wow_races.build`. Never hand-edit.
"""


def write_doc(path: Path, doc: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


def _int(value: str | None) -> int:
    return int(float(value or 0))


def variant_docs(variants: list[Variant]) -> list[dict[str, Any]]:
    return [{"classes": list(v.classes) if v.classes is not None else None, "text": v.text} for v in variants]


def racial_doc(race_slug: str, forever: Racial | None, classic: Racial | None, status: str) -> dict[str, Any]:
    shown = forever or classic
    assert shown is not None
    doc: dict[str, Any] = {
        "key": f"{race_slug}-{slug(shown.name)}",
        "name": shown.name,
        "kind": shown.kind,
        "status": status,
        "icon": shown.icon or (classic.icon if classic else 0),
        "variants": variant_docs(forever.variants) if forever else [],
    }
    if forever is not None and classic is not None and classic.name != forever.name:
        doc["wasName"] = classic.name
    if (forever is not None and not forever.full) or (classic is not None and not classic.full):
        doc["partial"] = True
    return doc


def _status_order(doc: Mapping[str, Any]) -> tuple[int, int, str]:
    return (doc["status"] == STATUS_REMOVED, doc["kind"] != "active", doc["name"])


def build_races(
    forever_races: Mapping[int, PlayableRace],
    forever_classes: Mapping[int, frozenset[str]],
    classic_classes: Mapping[int, frozenset[str]],
    forever_racials: Mapping[int, list[Racial]],
    classic_racials: Mapping[int, list[Racial]],
    start_zones: Mapping[int, str],
    ui_maps: Mapping[str, int],
    zone_names: Mapping[int, str],
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """The Forever-side race docs, and the Classic side by race id."""
    races: list[dict[str, Any]] = []
    classic_side: dict[str, Any] = {}
    for race in sorted(forever_races.values(), key=lambda r: race_order(r, r.id not in classic_classes)):
        race_slug = slug(race.name)
        classes = forever_classes[race.id]
        was = classic_classes.get(race.id, frozenset())
        racials: list[dict[str, Any]] = []
        classic_texts: dict[str, Any] = {}
        for f, c in pair_racials(forever_racials.get(race.id, []), classic_racials.get(race.id, [])):
            status = racial_status(f, c)
            doc = racial_doc(race_slug, f, c, status)
            racials.append(doc)
            if c is not None and status != "unchanged" and status != "new":
                classic_texts[doc["key"]] = {"variants": variant_docs(c.variants)}
        doc: dict[str, Any] = {
            "id": race.id,
            "slug": race_slug,
            "name": race.name,
            "faction": race.faction,
            "newInForever": race.id not in classic_classes,
            "classes": sorted(classes),
            "newClasses": sorted(classes - was) if was else [],
            "racials": sorted(racials, key=_status_order),
        }
        if race.id in UNCONFIRMED_START_ZONES and race.id not in start_zones:
            map_id = UNCONFIRMED_START_ZONES[race.id]
            doc["startZone"] = {"name": zone_names[map_id], "uiMapId": map_id}
        races.append(doc)
        side: dict[str, Any] = {"racials": classic_texts}
        if race.id in start_zones:
            name = start_zones[race.id]
            side["startZone"] = {"name": name, "uiMapId": ui_maps.get(name)}
        if side["racials"] or "startZone" in side:
            classic_side[str(race.id)] = side
    return races, classic_side


def client_racials(
    races: Mapping[int, PlayableRace],
    classes: Mapping[int, frozenset[str]],
    skill_lines: list[dict[str, str]],
    skill_race_class: list[dict[str, str]],
    abilities: list[dict[str, str]],
    book: Any,
    passive: Mapping[int, bool],
    icons: Mapping[int, int],
) -> dict[int, list[Racial]]:
    bits = {r.id: r.bit for r in races.values()}
    owners = line_races(skill_race_class, racial_lines(skill_lines), bits)
    spells = racial_spells(abilities, owners, bits, book.names, book.descriptions)
    out: dict[int, list[Racial]] = {}
    for race in races:
        mine = [s for s in spells if s.race == race]
        out[race] = group_racials(mine, classes[race], book, passive, icons)
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the WoW Forever races page's data.")
    parser.add_argument("--hotfix-cache", help="the Forever client's _forever_/Cache/ADB/enUS/DBCache.bin")
    args = parser.parse_args()

    forever = load_forever_tables(hotfix_cache_path(args.hotfix_cache), FOREVER_TABLES)
    tables = {name: forever.table(name) for name in FOREVER_TABLES}
    book = forever_book(tables)
    era = {"branch": WAGO_ERA_BRANCH, "build": WAGO_ERA_BUILD}
    dump = read_dump(cmangos_dump(), {"spell_template", "playercreateinfo"})
    era_misc = wago_table("SpellMisc", **era)
    classic = classic_book(
        wago_table("Spell", **era),
        wago_table("SpellName", **era),
        wago_table("SpellDuration", **era),
        wago_table("SpellRadius", **era),
        dump["spell_template"],
    )

    forever_classes = race_classes(wago_table("CharBaseInfo", hotfixes=True))
    classic_classes = race_classes(wago_table("CharBaseInfo", **era))
    forever_races = playable_races(wago_table("ChrRaces", hotfixes=True), forever_classes)
    classic_races = playable_races(wago_table("ChrRaces", **era), classic_classes)

    print("Reading racials...", flush=True)
    forever_racials = client_racials(
        forever_races, forever_classes,
        wago_table("SkillLine", hotfixes=True), wago_table("SkillRaceClassInfo", hotfixes=True),
        tables["SkillLineAbility"], book, passive_spells(tables["SpellMisc"]), forever_icons(tables["SpellMisc"]),
    )
    classic_racials = client_racials(
        classic_races, classic_classes,
        wago_table("SkillLine", **era), wago_table("SkillRaceClassInfo", **era),
        wago_table("SkillLineAbility", **era), classic, passive_spells(era_misc), forever_icons(era_misc),
    )

    areas = {_int(r["ID"]): r["AreaName_lang"] for r in wago_table("AreaTable")}
    start_zones = {race: areas[zone] for race, zone in classic_start_zones(dump["playercreateinfo"]).items() if zone in areas}
    world_zones = json.loads(ZONES_PATH.read_text(encoding="utf-8"))["zones"]
    races, classic_side = build_races(
        forever_races, forever_classes, classic_classes, forever_racials, classic_racials,
        start_zones, ui_map_by_name(world_zones), {_int(str(z["id"])): str(z["name"]) for z in world_zones},
    )

    statuses = Counter(r["status"] for race in races for r in race["racials"])
    counts = {"races": len(races), "racials": sum(statuses.values()), **{k: statuses[k] for k in sorted(statuses)}}
    write_doc(RACES_DIR / "races.json", {
        "source": forever.source(),
        "classicSource": f"wago.tools DB2 {WAGO_ERA_BRANCH} {WAGO_ERA_BUILD}",
        "attribution": ATTRIBUTION,
        "clientBuild": WAGO_BUILD,
        "classicBuild": WAGO_ERA_BUILD,
        "counts": counts,
        "races": races,
    })
    write_doc(CLASSIC_DIR / "racials.json", {
        "source": (
            f"Classic Era client ({WAGO_ERA_BRANCH} {WAGO_ERA_BUILD}) wording with cmangos classic-db "
            f"{CMANGOS_COMMIT[:12]} numbers and playercreateinfo (GPL-3.0)"
        ),
        "races": classic_side,
    })
    shutil.copyfile(CLASSIC_LICENSE, CLASSIC_DIR / "LICENSE")
    (CLASSIC_DIR / "README.md").write_text(
        CLASSIC_README.format(commit=CMANGOS_COMMIT, era_branch=WAGO_ERA_BRANCH, era_build=WAGO_ERA_BUILD),
        encoding="utf-8",
    )
    print(f"counts: {counts}")
    partial = [r["key"] for race in races for r in race["racials"] if r.get("partial")]
    if partial:
        print(f"  a value isn't in the game files (shown as ?): {', '.join(partial)}")
    print(f"-> {RACES_DIR}")


if __name__ == "__main__":
    main()
