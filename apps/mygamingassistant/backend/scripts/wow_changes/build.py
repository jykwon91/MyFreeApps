"""Build the WoW Forever "Changes vs Classic" feed (``/wow-forever/changes``).

Usage (from ``apps/mygamingassistant/backend``, after the Items and Talents builds)::

    python -m scripts.wow_changes.build [--hotfix-cache <DBCache.bin>]

Every row is a diff of two clients' tables, never hand-written: the Forever
client (wago.tools ``wowf`` with the hotfix layers the item build uses — the
operator's ``DBCache.bin`` is required) against the Classic Era client
(``wow_classic_era``). Talents come from the talent calculator's own output;
items from the compare page's item list; class spells, quests, zones and
maps from the client tables here. Quest names come only from the operator's
own ``questcache.wdb``, through the quest pages' ``questSeen.json`` (run the
Quest pages build first): it keeps quests a patch emptied from the cache.

Writes ``data/changes/``:

* ``index.json`` — builds, counts per category and what couldn't be compared;
* ``items.json`` (changed) + ``itemsNew.json``, ``quests.json``, ``zones.json`` — lazy shards;
* ``classic/talents.json``, ``classic/spells.json`` — their Classic side is
  the Classic Era wording filled with cmangos classic-db numbers (GPL-3.0,
  LICENSE + README next to them), as in the talent calculator.

Each row's ``since`` is worked out from the previous run's files
(``stamp.py``) before they're overwritten. Game data © Blizzard Entertainment.
Never hand-edit the output.
"""
from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path
from typing import Any

from scripts.wow_changes.entry import KIND_CHANGED, KIND_NEW, Change
from scripts.wow_changes.items import item_changes, new_other_items
from scripts.wow_changes.spells import SpellGaps, class_spells, spell_changes
from scripts.wow_changes.stamp import previous_build, stamp
from scripts.wow_changes.talents import live_talent_spells, talent_changes
from scripts.wow_changes.world import quest_changes, zone_changes
from scripts.wow_dungeons.quests import earlier_seen
from scripts.wow_food.build import CLASSIC_LICENSE, WOW_DATA_DIR
from scripts.wow_gear.build import write_json
from scripts.wow_items.build import write_rows
from scripts.wow_items.forever_items import (
    ITEM_TABLES,
    hotfix_cache_path,
    load_forever_tables,
)
from scripts.wow_macros.build import CLASS_LINES
from scripts.wow_quests.build import read_quest_seen
from scripts.wow_talents.books import FOREVER_BOOK_TABLES, classic_book, forever_book
from scripts.wow_talents.talents import rank_spells
from scripts.wow_world_map.sources import (
    CMANGOS_COMMIT,
    WAGO_BUILD,
    WAGO_ERA_BRANCH,
    WAGO_ERA_BUILD,
    cmangos_dump,
    wago_table,
)
from scripts.wow_world_map.sql_dump import read_dump

CHANGES_DIR = WOW_DATA_DIR / "changes"
CLASSIC_DIR = CHANGES_DIR / "classic"
INDEX_PATH = CHANGES_DIR / "index.json"
TALENTS_DIR = WOW_DATA_DIR / "talents"
# The spell books both sides of the class-spell diff read, and the client's talent ranks it leaves out.
FOREVER_TABLES = ("Talent", *FOREVER_BOOK_TABLES)
ITEMS_PATH = WOW_DATA_DIR / "items" / "items.json"
ZONES_PATH = WOW_DATA_DIR / "worldMap" / "zones.json"

# (category, the rows' kind or None for all, shard path relative to ``data/changes/``).
# Items are split so no shard tops ~600 KB. The index lists each category's
# shards for the page; ``data/changes/changeCategories.ts`` lists the same ids.
SHARDS: tuple[tuple[str, str | None, str], ...] = (
    ("talents", None, "classic/talents.json"),
    ("spells", None, "classic/spells.json"),
    ("items", KIND_CHANGED, "items.json"),
    ("items", KIND_NEW, "itemsNew.json"),
    ("quests", None, "quests.json"),
    ("zones", None, "zones.json"),
)
ATTRIBUTION = "Diffed from the WoW Forever and Classic Era clients via wago.tools. Game data © Blizzard Entertainment."

CLASSIC_README = """# Changes vs Classic — Classic talent and spell text

`talents.json` and `spells.json` hold the "Classic" side of the feed's talent
and class-spell rows: the Classic Era client's own tooltip wording
(wago.tools, `{era_branch}` {era_build}) filled with the 1.12 numbers from
[cmangos classic-db](https://github.com/cmangos/classic-db) at commit
`{commit}` (`spell_template`), licensed GPL-3.0 — see `LICENSE`. No cmangos
code is used. The "Forever" side is the Forever client's tooltip.

Generated by `python -m scripts.wow_changes.build`. Never hand-edit.
"""


def _read(path: Path) -> Any | None:
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def previous_entries(index: dict[str, Any] | None) -> dict[str, dict[str, Any]] | None:
    """The last run's rows by key, across every shard; None when there was no last run."""
    if index is None:
        return None
    out: dict[str, dict[str, Any]] = {}
    for _, _, shard in SHARDS:
        doc = _read(CHANGES_DIR / shard)
        for entry in (doc or {}).get("entries", []):
            out[entry["key"]] = entry
    return out


def _counts(changes: list[Change]) -> dict[str, int]:
    new = sum(1 for c in changes if c.kind == KIND_NEW)
    return {"changed": len(changes) - new, "new": new}


def _talent_docs() -> tuple[dict[str, Any], dict[str, Any]]:
    forever = {p.stem: _read(p) for p in sorted(TALENTS_DIR.glob("*.json"))}
    classic = {p.stem: _read(p) for p in sorted((TALENTS_DIR / "classic").glob("*.json"))}
    return forever, classic


def _items() -> list[dict[str, Any]]:
    doc = _read(ITEMS_PATH)
    return [dict(zip(doc["columns"], row)) for row in doc["items"]]


def _line_class() -> dict[int, str]:
    return {line: class_id for class_id, lines in CLASS_LINES.items() for line in lines}


def _ids(rows: list[dict[str, str]]) -> set[int]:
    return {int(r["ID"]) for r in rows}


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the WoW Forever Changes vs Classic feed.")
    parser.add_argument("--hotfix-cache", help="the Forever client's _forever_/Cache/ADB/enUS/DBCache.bin")
    args = parser.parse_args()
    hotfix_cache = hotfix_cache_path(args.hotfix_cache)

    era = {"branch": WAGO_ERA_BRANCH, "build": WAGO_ERA_BUILD}
    forever = load_forever_tables(hotfix_cache, (*ITEM_TABLES, *FOREVER_TABLES))
    book = forever_book({name: forever.table(name) for name in FOREVER_TABLES})
    era_spells = wago_table("Spell", **era)
    era_names = wago_table("SpellName", **era)
    classic = classic_book(
        era_spells,
        era_names,
        wago_table("SpellDuration", **era),
        wago_table("SpellRadius", **era),
        wago_table("SpellRange", **era),
        read_dump(cmangos_dump(), {"spell_template"})["spell_template"],
    )
    print("Diffing talents...", flush=True)
    forever_talents, classic_talents = _talent_docs()
    talents = talent_changes(forever_talents, classic_talents)

    print("Diffing class spells...", flush=True)
    line_class = _line_class()
    spell_gaps = SpellGaps()
    spells = spell_changes(
        class_spells(
            wago_table("SkillLineAbility"),
            line_class,
            book.names,
            {int(r["ID"]): r.get("NameSubtext_lang") or "" for r in forever.table("Spell")},
            {s for r in forever.table("Talent") for s in rank_spells(r)} | live_talent_spells(forever_talents.values()),
        ),
        class_spells(
            wago_table("SkillLineAbility", **era),
            line_class,
            {int(r["ID"]): r["Name_lang"] for r in era_names},
            {int(r["ID"]): r.get("NameSubtext_lang") or "" for r in era_spells},
            # Classic's talent spells stay in, so a talent Forever made a trainer spell isn't "new".
            set(),
        ),
        book,
        classic,
        spell_gaps,
    )

    print("Diffing items...", flush=True)
    era_sparse = {int(r["ID"]): r for r in wago_table("ItemSparse", **era, hotfixes=True)}
    gear = _items()
    item_class = {i: int(r.get("ClassID") or -1) for i, r in forever.rows["Item"].items()}
    items = item_changes(gear, era_sparse)
    other_items, unlisted_new_items = new_other_items(
        forever.table("ItemSparse"), item_class, set(era_sparse), {g["id"] for g in gear},
    )

    print("Diffing quests, zones and maps...", flush=True)
    seen_doc = read_quest_seen()
    quests, unnamed_quests = quest_changes(
        _ids(wago_table("QuestV2", hotfixes=True)),
        _ids(wago_table("QuestV2", **era, hotfixes=True)),
        earlier_seen(seen_doc),
    )
    world_map_ids = {z["id"] for z in _read(ZONES_PATH)["zones"]}
    zones = zone_changes(
        wago_table("UiMap"), _ids(wago_table("UiMap", **era)),
        wago_table("Map"), _ids(wago_table("Map", **era)),
        world_map_ids,
    )

    by_category = {"talents": talents, "spells": spells, "items": items + other_items, "quests": quests, "zones": zones}
    old_index = _read(INDEX_PATH)
    old_entries = previous_entries(old_index)
    index = {
        "source": forever.source(),
        "classicSource": f"wago.tools DB2 {WAGO_ERA_BRANCH} {WAGO_ERA_BUILD}",
        "attribution": ATTRIBUTION,
        "build": WAGO_BUILD,
        "classicBuild": WAGO_ERA_BUILD,
        "previousBuild": previous_build(old_index, WAGO_BUILD),
        "questsSeenOn": seen_doc["seenOn"],
        "counts": {category: _counts(changes) for category, changes in by_category.items()},
        "shards": {category: [path for c, _, path in SHARDS if c == category] for category in by_category},
        "gaps": {
            "spellsIncomplete": spell_gaps.incomplete,
            "spellsNotInClient": spell_gaps.not_in_client,
            "itemsUnlisted": unlisted_new_items,
            "questsUnnamed": unnamed_quests,
        },
    }
    for category, kind, path in SHARDS:
        docs = [c.doc() for c in by_category[category] if kind is None or c.kind == kind]
        entries = stamp(docs, old_entries, WAGO_BUILD)
        write_rows(CHANGES_DIR / path, {"category": category, "build": WAGO_BUILD}, "entries", entries)
    write_json(INDEX_PATH, index)
    shutil.copyfile(CLASSIC_LICENSE, CLASSIC_DIR / "LICENSE")
    (CLASSIC_DIR / "README.md").write_text(
        CLASSIC_README.format(era_branch=WAGO_ERA_BRANCH, era_build=WAGO_ERA_BUILD, commit=CMANGOS_COMMIT),
        encoding="utf-8",
    )

    for category, counts in index["counts"].items():
        print(f"{category}: {counts['changed']} changed, {counts['new']} new")
    print(f"gaps: {index['gaps']}")
    print(f"-> {CHANGES_DIR}")


if __name__ == "__main__":
    main()
